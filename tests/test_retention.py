"""留存：第 N 日留存只看 cohort_date + N 当天是否活跃；新增 / 活跃两种同期群。"""
from tests.conftest import ev

TASKS = ["dwd_user_behavior_inc", "dws_user_action_1d", "dws_user_milestone_td", "ads_user_retention"]


def test_day1_and_day3_retention(wh):
    events = [
        ev(1, "pv", "2017-11-25 10:00:00"), ev(1, "pv", "2017-11-26 10:00:00"),          # 次日留存
        ev(2, "pv", "2017-11-25 10:00:00"), ev(2, "buy", "2017-11-28 10:00:00"),         # 第 3 日留存
        ev(3, "pv", "2017-11-25 10:00:00"), ev(3, "fav", "2017-11-27 10:00:00"),         # 只在第 2 天回来：都不算
        ev(4, "pv", "2017-11-26 10:00:00"), ev(4, "pv", "2017-11-27 10:00:00"),          # 11-26 新增，次日留存
        ev(5, "pv", "2017-11-26 10:00:00"),                                               # 11-26 新增，未留存
        ev(6, "pv", "2017-11-25 09:00:00"), ev(6, "cart", "2017-11-25 09:30:00"),        # 同一天多次行为只算一人
        ev(6, "pv", "2017-11-26 09:00:00"),
    ]
    wh.load(events)
    wh.run("2017-11-25", "2017-11-28", tasks=TASKS)

    got = {(r.dt, r.cohort_date, r.cohort_type, r.retention_day): (r.cohort_size, r.retained_cnt, r.retention_rate)
           for r in wh.rows("SELECT * FROM {db}.ads_user_retention")}
    assert got == {
        # 计算日 11-26：11-25 同期群的次日留存（第一天所有人都算"新增"，两种同期群一样）
        ("2017-11-26", "2017-11-25", "new", 1): (4, 2, 0.5),
        ("2017-11-26", "2017-11-25", "active", 1): (4, 2, 0.5),
        # 计算日 11-27：11-26 新增只有 u4、u5；11-26 活跃有 u1、u4、u5、u6
        ("2017-11-27", "2017-11-26", "new", 1): (2, 1, 0.5),
        ("2017-11-27", "2017-11-26", "active", 1): (4, 1, 0.25),
        # 计算日 11-28：11-25 同期群的第 3 日留存只有 u2；11-27 没有新增用户 → 不产出 new 行
        ("2017-11-28", "2017-11-25", "new", 3): (4, 1, 0.25),
        ("2017-11-28", "2017-11-25", "active", 3): (4, 1, 0.25),
        ("2017-11-28", "2017-11-27", "active", 1): (2, 0, 0.0),
    }
